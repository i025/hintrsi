def _load_system_prompt():
    """加载系统 prompt。

    优先级：
    1. SYSTEM_PROMPT_FILE 环境变量 — 指定文件全文替换 system prompt
    2. APPEND_SYSTEM_PROMPT_FILE 环境变量 — 在默认 claude_code preset 之后
       追加文件内容（以 <system-reminder> block 形式嵌入，不覆盖 preset）
    3. 默认 claude_code preset
    """
    prompt_file = os.getenv("SYSTEM_PROMPT_FILE")
    if prompt_file:
        p = Path(prompt_file)
        if p.is_file():
            return p.read_text(encoding="utf-8")
        else:
            logger.warning(f"SYSTEM_PROMPT_FILE not found: {prompt_file}, falling back to preset")

    append_file = os.getenv("APPEND_SYSTEM_PROMPT_FILE")
    if append_file:
        p = Path(append_file)
        if p.is_file():
            append_content = p.read_text(encoding="utf-8").strip()
            if append_content:
                wrapped = f"<system-reminder>\n{append_content}\n</system-reminder>"
                logger.info(
                    f"Appending system prompt from {append_file} "
                    f"({len(wrapped)} chars, wrapped as system-reminder)"
                )
                return {"type": "preset", "preset": "claude_code", "append": wrapped}
            logger.warning(f"APPEND_SYSTEM_PROMPT_FILE is empty: {append_file}, using default preset")
        else:
            logger.warning(f"APPEND_SYSTEM_PROMPT_FILE not found: {append_file}, using default preset")

    return {"type": "preset", "preset": "claude_code"}


SYSTEM_PROMPT_CONFIG_LOG_PATH = Path(
    os.getenv("SYSTEM_PROMPT_CONFIG_LOG_PATH", "/tmp/system_prompt_config.json")
)


def _log_system_prompt_config(system_prompt) -> None:
    """Record the resolved system-prompt configuration before agent startup.

    Writes a JSON snapshot to SYSTEM_PROMPT_CONFIG_LOG_PATH so the runner can
    copy it out and we can verify (post-hoc) which mode was active and whether
    the hint append content was present.

    Modes:
      - "replace":  SYSTEM_PROMPT_FILE full replacement (str)
      - "append":   APPEND_SYSTEM_PROMPT_FILE wrapped as system-reminder (dict)
      - "preset":   default claude_code preset, no append (dict)
    """
    import datetime

    env_spf = os.getenv("SYSTEM_PROMPT_FILE", "")
    env_aspf = os.getenv("APPEND_SYSTEM_PROMPT_FILE", "")

    if isinstance(system_prompt, str):
        mode = "replace"
        record = {
            "timestamp": datetime.datetime.now().isoformat(timespec="seconds"),
            "mode": mode,
            "source_env": {"SYSTEM_PROMPT_FILE": env_spf, "APPEND_SYSTEM_PROMPT_FILE": env_aspf},
            "char_count": len(system_prompt),
            "contains_system_reminder": "<system-reminder>" in system_prompt,
            "full_text": system_prompt,
        }
    elif isinstance(system_prompt, dict):
        preset = system_prompt.get("preset", "")
        append = system_prompt.get("append", "")
        mode = "append" if append else "preset"
        record = {
            "timestamp": datetime.datetime.now().isoformat(timespec="seconds"),
            "mode": mode,
            "preset": preset,
            "source_env": {"SYSTEM_PROMPT_FILE": env_spf, "APPEND_SYSTEM_PROMPT_FILE": env_aspf},
            "append_char_count": len(append) if append else 0,
            "contains_system_reminder": "<system-reminder>" in append if append else False,
            "append_text": append if append else None,
        }
    else:
        record = {
            "timestamp": datetime.datetime.now().isoformat(timespec="seconds"),
            "mode": "unknown",
            "value_type": str(type(system_prompt)),
        }

    try:
        SYSTEM_PROMPT_CONFIG_LOG_PATH.write_text(
            json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        logger.info(
            "system_prompt config logged: mode=%s -> %s",
            record.get("mode"), SYSTEM_PROMPT_CONFIG_LOG_PATH,
        )
    except Exception:
        logger.exception("failed to write system_prompt config log")


def create_agent_options(
    working_dir: str,
    resume_session_id: Optional[str] = None,
    fork_session: bool = False,
    online_teacher: Optional[OnlineTeacher] = None,
) -> ClaudeAgentOptions:
    """创建 agent 配置选项"""
    sandbox_settings: SandboxSettings = {
        "enabled": True,
        "autoAllowBashIfSandboxed": True,
        "network": {"allowLocalBinding": True}
    }

    resolved_system_prompt = _load_system_prompt()
    # Log the resolved system-prompt config before startup (verifies hint append)
    _log_system_prompt_config(resolved_system_prompt)

    kwargs: Dict[str, Any] = dict(
        permission_mode="bypassPermissions",
        system_prompt=resolved_system_prompt,
        cwd=working_dir,
        env={"BUN_JSC_useJIT": "0", "ENABLE_TOOL_SEARCH": "false"},
        stderr=lambda line: logger.warning("Claude CLI stderr: %s", line),
        sandbox=sandbox_settings,
        setting_sources=["user", "project"],
        disallowed_tools=[
            "ExitPlanMode", "NotebookEdit",
            # Block all outbound-lookup tools so the agent solves the task
            # from the local codebase instead of retrieving the upstream fix.
            "WebSearch", "WebFetch",
            "AskUserQuestion", "EnterPlanMode",
        ],
    )
    if os.getenv("ANTHROPIC_MODEL"):
        kwargs["model"] = DEFAULT_MODEL
    if online_teacher is not None:
        kwargs["hooks"] = {
            event: [HookMatcher(hooks=[online_teacher.on_tool], timeout=720)]
            for event in ("PreToolUse", "PostToolUse", "PostToolUseFailure")
        }
    # 会话恢复:resume 指定 session_id 继续对话;fork_session 在 resume
    # 基础上分叉出新会话(不污染原会话文件)。仅当提供 resume_session_id
    # 时 fork_session 才有意义。
    if resume_session_id:
        kwargs["resume"] = resume_session_id
        if fork_session:
            kwargs["fork_session"] = True

    return ClaudeAgentOptions(**kwargs)

def save_results(
    trajectories: Dict,
    metadata: Dict,
    patch_bytes: bytes,
    result_file: Path,
    patch_file: Path
) -> None:
    """保存结果到文件"""
    result = {"trajectories": trajectories, "metadata": metadata}
    
    try:
        with open(result_file, 'w', encoding='utf-8') as f:
            json.dump(result, f, ensure_ascii=False, indent=4)
        with open(patch_file, 'wb') as f:
            f.write(patch_bytes)
        logger.info(f"结果已保存至: {result_file}, {patch_file}")
    except Exception as e:
        logger.error(f"保存结果失败: {e}")
        raise


async def run_agent_execution(
    problem_statement: str,
    working_dir: str,
    options: ClaudeAgentOptions,
    base_commit = None,
    init_first: bool = False,
    extra_message: Optional[str] = None,
    is_resume: bool = False,
    commit_file: Optional[str] = None,
    trajectories: Optional[Dict] = None,
    metadata: Optional[Dict] = None,
) -> Dict[str, Any]:
    """执行 agent 并收集元数据

    若提供 ``trajectories`` dict,则将 AssistantMessage / UserMessage 按
    ``parent_tool_use_id`` 分流:主 agent 消息拼为 JSONL 字符串写入
    ``trajectories["main_agent"]``,子 agent 消息分组写入
    ``trajectories["sub_agent"]`` 列表。
    """
    if metadata is None:
        metadata = {}
    commit_file = commit_file or "/tmp/base_commit.txt"
    if trajectories is None:
        trajectories = {"main_agent": "", "sub_agent": []}
    main_lines: List[str] = []
    sub_groups: Dict[str, List[str]] = {}

    if is_resume:
        # resume 模式:只对当前工作区做快照 commit,绝不 checkout
        # base_commit —— 否则会丢掉上一轮 agent 留下的修改。
        # base_commit.txt 由调用方(run_sdk)负责写入,这里不覆盖。
        commit_cmd = (
            'git config --global user.email "runner@example.com" && '
            'git config --global user.name "Runner" && '
            'git commit --allow-empty --no-verify -m "Execution Snapshot (resume)"'
        )
    else:
        # 首轮:快照 commit → checkout base_commit → 记录 base_commit
        checkout_cmd = f'git checkout {base_commit} && ' if base_commit else ''
        commit_cmd = (
            'git config --global user.email "runner@example.com" && '
            'git config --global user.name "Runner" && '
            'git commit --allow-empty --no-verify -m "Execution Snapshot" && '
            f'{checkout_cmd}'
            f'git rev-parse HEAD > {commit_file}'
        )
    if os.getenv("TEACHER_MODE") != "1":
        run_command(commit_cmd, cwd=working_dir)

    try:
        async with ClaudeSDKClient(options=options) as client:
            # 先执行 /init 让 agent 熟悉项目结构(仅首轮)
            if init_first and not is_resume:
                logger.info("Running /init to initialize project context...")
                await client.query("/init")
                async for message in client.receive_response():
                    if isinstance(message, ResultMessage):
                        logger.info(f"/init completed: {asdict(message).get('result', '')[:200]}")

            # resume 时发送 hint(extra_message),否则发送原始问题
            if is_resume and extra_message:
                logger.info("Resuming session with hint message...")
                await client.query(extra_message)
            else:
                await client.query(problem_statement)

            async for message in client.receive_response():
                message_dict = asdict(message)
                logger.info("Received claude code message: %s", message_dict)
                if isinstance(message, SystemMessage):
                    metadata["SystemMessage"] = message_dict
                elif isinstance(message, ResultMessage):
                    metadata["ResultMessage"] = message_dict
                    logger.info(message)
                elif isinstance(message, (AssistantMessage, UserMessage)):
                    record = {
                        "type": "assistant" if isinstance(message, AssistantMessage) else "user",
                        "message": message_dict,
                    }
                    line = json.dumps(record, ensure_ascii=False)
                    parent_id = message_dict.get("parent_tool_use_id")
                    if parent_id:
                        sub_groups.setdefault(parent_id, []).append(line)
                    else:
                        main_lines.append(line)
    finally:
        trajectories["main_agent"] = "\n".join(main_lines)
        trajectories["sub_agent"] = ["\n".join(lines) for lines in sub_groups.values()]
    logger.info(
        "轨迹收集完成: main_agent %d 条消息, sub_agent %d 组",
        len(main_lines), len(sub_groups),
    )
    return metadata


async def run_sdk(
    problem_statement: str,
    working_dir: str,
    log_path: Path = DEFAULT_LOG_PATH,
    output_dir: Path = DEFAULT_OUTPUT_DIR,
    base_commit = None,
    init_first: bool = False,
    resume_session_id: Optional[str] = None,
    fork_session: bool = False,
    extra_message: Optional[str] = None,
) -> None:
    """主执行函数"""
    is_resume = bool(resume_session_id)
    logger.info(
        f"开始执行，工作目录: {working_dir}, resume={is_resume}"
        + (f" (session={resume_session_id})" if is_resume else "")
    )

    teacher_mode = os.getenv("TEACHER_MODE") == "1"
    progress_url = os.getenv("TEACHER_PROGRESS_URL")
    online_teacher = None
    if progress_url and not teacher_mode:
        online_teacher = OnlineTeacher(
            progress_url, os.environ["EXPERIMENT_SESSION"],
            os.getenv("EXPERIMENT_TASK", ""), output_dir,
        )
    options = create_agent_options(
        working_dir,
        resume_session_id=resume_session_id,
        fork_session=fork_session,
        online_teacher=online_teacher,
    )
    trajectories = {"main_agent": "", "sub_agent": []}
    metadata = {}

    base_commit_file = output_dir / "base_commit.txt"

    started = time.monotonic()
    try:
        # 执行 agent
        metadata = await run_agent_execution(
            problem_statement, working_dir, options,
            base_commit=base_commit, init_first=init_first,
            extra_message=extra_message, is_resume=is_resume,
            commit_file=str(base_commit_file),
            trajectories=trajectories,
            metadata=metadata,
        )
        if "ResultMessage" not in metadata:
            metadata["status"] = "incomplete"
            metadata["error_log"] = "SDK ended without a final ResultMessage"
        elif metadata.get("ResultMessage", {}).get("is_error"):
            metadata["status"] = "incomplete"
        elif online_teacher is not None and online_teacher.error:
            metadata["status"] = "incomplete"
            metadata["error_log"] = online_teacher.error
        else:
            metadata["status"] = "completed"
    except BaseException as exc:
        logger.exception("Agent execution did not complete")
        metadata["status"] = "incomplete"
        metadata["error_log"] = str(exc) or type(exc).__name__
        raise
    finally:
        metadata["wall_seconds"] = time.monotonic() - started
        if online_teacher is not None:
            metadata["teacher_wait_seconds"] = online_teacher.wait_seconds
            metadata["teacher_checks"] = online_teacher.checks
            metadata["main_tool_count"] = online_teacher.tool_count
        if teacher_mode:
            (output_dir / "trajs.json").write_text(
                json.dumps({"trajectories": trajectories, "metadata": metadata},
                           ensure_ascii=False, indent=4), encoding="utf-8"
            )
        else:
            _save_student_results(working_dir, base_commit, base_commit_file,
                                  trajectories, metadata, output_dir)


def _save_student_results(working_dir, base_commit, base_commit_file,
                          trajectories, metadata, output_dir):
    # 获取 patch(始终基于原始 base_commit,生成累积 patch)
    if base_commit_file.exists():
        base_commit_val = base_commit_file.read_text(encoding='utf-8').strip()
        patch_bytes = get_smart_diff(working_dir, base_commit_val)
    elif base_commit:
        # resume 且首轮 base_commit.txt 在别的 output_dir 时,
        # 用 --base_commit 参数兜底写入,保证 get_smart_diff 可用
        logger.info(f"base_commit.txt 不存在,使用参数 base_commit={base_commit}")
        base_commit_file.parent.mkdir(parents=True, exist_ok=True)
        base_commit_file.write_text(base_commit, encoding='utf-8')
        patch_bytes = get_smart_diff(working_dir, base_commit)
    else:
        logger.warning(f"未找到 base_commit.txt，跳过 patch 生成: {base_commit_file}")
        patch_bytes = b""

    # 保存结果
    save_results(
        trajectories, metadata, patch_bytes,
        output_dir / "trajs.json",
        output_dir / "patch.diff"
    )


def parse_args() -> argparse.Namespace:
    """解析命令行参数"""
    parser = argparse.ArgumentParser(description="Claude Code SDK Quick Start")
    problem = parser.add_mutually_exclusive_group()
    problem.add_argument("--problem_statement", default=None, type=str,
                         help="问题描述(首轮必填;resume 时可省略)")
    problem.add_argument("--problem_statement_file", default=None, type=str,
                         help="UTF-8 file containing the complete problem statement")
    parser.add_argument("--cwd", required=True, type=str, help="工作目录")
    parser.add_argument("--base_commit", default=None,
                        help="基础 commit(resume 时用于兜底生成累积 patch)")
    parser.add_argument("--init", action="store_true", help="先执行 /init 初始化项目上下文")
    parser.add_argument("--log_path", type=str, default=str(DEFAULT_LOG_PATH), help="日志文件路径")
    parser.add_argument("--output_dir", type=str, default=str(DEFAULT_OUTPUT_DIR), help="输出目录")
    parser.add_argument("--resume_session_id", default=None, type=str,
                        help="恢复指定会话继续对话(多轮反馈 loop 使用)")
    parser.add_argument("--fork_session", action="store_true",
                        help="配合 --resume_session_id,分叉出新会话而不污染原会话")
    extra = parser.add_mutually_exclusive_group()
    extra.add_argument("--extra_message", default=None, type=str,
                       help="resume 时发送的额外消息(即 reviewer hint)")
    extra.add_argument("--extra_message_file", default=None, type=str,
                       help="UTF-8 file containing the complete resume message")
    args = parser.parse_args()
    if args.problem_statement_file is not None:
        # Match the previous $(cat file) argument: strip trailing LF only.
        with Path(args.problem_statement_file).open(encoding="utf-8", newline="") as stream:
            args.problem_statement = stream.read().rstrip("\n")
    if args.extra_message_file is not None:
        with Path(args.extra_message_file).open(encoding="utf-8", newline="") as stream:
            args.extra_message = stream.read().rstrip("\n")
    return args


async def main():
    """入口函数"""
    args = parse_args()
    setup_logging(str(Path(args.log_path)))
    Path(args.output_dir).mkdir(parents=True, exist_ok=True)

    is_resume = bool(args.resume_session_id)
    if not is_resume and not args.problem_statement:
        raise SystemExit("--problem_statement or --problem_statement_file is required when not resuming")
    if is_resume and not args.extra_message:
        raise SystemExit("--extra_message or --extra_message_file is required when --resume_session_id is set")

    problem_statement = args.problem_statement or ""

    await run_sdk(
        problem_statement=problem_statement,
        working_dir=args.cwd,
        log_path=Path(args.log_path),
        output_dir=Path(args.output_dir),
        base_commit=args.base_commit,
        init_first=args.init,
        resume_session_id=args.resume_session_id,
        fork_session=args.fork_session,
        extra_message=args.extra_message,
    )


if __name__ == "__main__":
    anyio.run(main)
