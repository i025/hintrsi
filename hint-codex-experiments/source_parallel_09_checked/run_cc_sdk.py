class JSONLHandler:
    """JSONL 文件读写工具"""
    
    @staticmethod
    def read(filepath: str) -> List[Dict]:
        """读取 JSONL 文件为 list"""
        data = []
        with open(filepath, 'r', encoding='utf-8') as f:
            for line in f:
                if line.strip():
                    data.append(json.loads(line))
        return data
    
    @staticmethod
    def write(filepath: str, data: List[Dict], append: bool = False) -> None:
        """写入 list 到 JSONL 文件"""
        mode = 'a' if append else 'w'
        with open(filepath, mode, encoding='utf-8') as f:
            for item in data:
                f.write(json.dumps(item, ensure_ascii=False) + '\n')
    
    @staticmethod
    def append_one(filepath: str, item: Dict) -> None:
        """追加单条记录到 JSONL"""
        with open(filepath, 'a', encoding='utf-8') as f:
            f.write(json.dumps(item, ensure_ascii=False) + '\n')


# ==================== 消息过滤工具 ====================
def normalize_content(content: Any) -> Any:
    """
    标准化 content，移除元数据字段
    支持 content 是 string 或 list 的情况
    """
    if content is None or isinstance(content, str):
        return content
    
    if isinstance(content, list):
        normalized = []
        for item in content:
            if isinstance(item, dict):
                # 只保留核心字段，移除元数据
                normalized_item = {
                    k: v for k, v in item.items() 
                    if k not in ('cache_control', 'id', 'tool_use_id')
                }
                normalized.append(normalized_item)
            else:
                normalized.append(item)
        return normalized
    
    return content

# ==================== Git 工具 ====================
def is_binary_file(filepath: Path) -> bool:
    """检测文件是否为二进制文件"""
    try:
        with open(filepath, 'rb') as f:
            return b'\0' in f.read(1024)
    except Exception:
        return True


def is_generated_file(filepath: Path) -> bool:
    """检测文件是否为自动生成的文件"""
    try:
        with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
            head = "".join(f.readline() for _ in range(5)).lower()
            return any(kw in head for kw in GENERATED_KEYWORDS)
    except Exception:
        return False


def get_smart_diff(repo_path: str, start_commit: str, end_commit: Optional[str] = None) -> bytes:
    """
    获取智能 git diff，排除二进制/自动生成/锁定文件
    """
    # Stage all changes (including new untracked files) so git diff can see them
    subprocess.run(["git", "add", "-A"], cwd=repo_path, capture_output=True)

    # 获取变更文件列表 (use --cached to include staged new files)
    diff_args = ["--cached", start_commit] + ([end_commit] if end_commit else [])
    cmd = ["git", "diff", "--name-only"] + diff_args
    
    try:
        result = subprocess.run(cmd, cwd=repo_path, capture_output=True, text=True, check=True)
    except subprocess.CalledProcessError as e:
        logger.error(f"获取变更文件失败: {e.stderr}")
        return b""

    changed_files = [f for f in result.stdout.strip().split('\n') if f.strip()]
    exclude_patterns = []
    
    for file_rel_path in changed_files:
        full_path = Path(repo_path) / file_rel_path

        if Path(file_rel_path).name in EXCLUDED_FILENAMES:
            exclude_patterns.append(f":!{file_rel_path}")
            continue
        
        # 跳过不存在的文件或目录
        if not full_path.exists() or full_path.is_dir():
            exclude_patterns.append(f":!{file_rel_path}")
            continue
        
        # 跳过二进制文件
        if is_binary_file(full_path):
            exclude_patterns.append(f":!{file_rel_path}")
            continue
        
        # 跳过自动生成的文件
        if is_generated_file(full_path):
            logger.info(f"检测到生成文件，跳过: {file_rel_path}")
            exclude_patterns.append(f":!{file_rel_path}")
            continue
        
        # 跳过锁定文件
        if file_rel_path.endswith(EXCLUDED_EXTENSIONS):
            exclude_patterns.append(f":!{file_rel_path}")
    
    # 构建最终 diff 命令
    final_cmd = ["git", "diff", "--binary"] + diff_args + ["--", "."] + exclude_patterns
    
    logger.debug(f"执行 diff: {' '.join(final_cmd)}")
    
    try:
        patch_result = subprocess.run(final_cmd, cwd=repo_path, capture_output=True, check=True)
        return patch_result.stdout.encode() if isinstance(patch_result.stdout, str) else patch_result.stdout
    except subprocess.CalledProcessError as e:
        logger.error(f"生成 patch 失败: {e.stderr}")
        return b""


def run_command(command: str, cwd: Optional[str] = None) -> str:
    """执行 shell 命令并返回输出"""
    try:
        result = subprocess.check_output(
            command, shell=True, cwd=cwd, stderr=subprocess.STDOUT, text=True
        )
        return result.strip()
    except subprocess.CalledProcessError:
        return ""

