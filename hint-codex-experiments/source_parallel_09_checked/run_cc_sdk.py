class OnlineTeacher:
    """Pause the main student at completed-tool checkpoints."""

    def __init__(self, url: str, session: str, task: str, output_dir: Path):
        if url not in {
            "http://172.17.0.1:8766/experiment/progress",
            "http://127.0.0.1:8766/experiment/progress",
            "http://localhost:8766/experiment/progress",
        }:
            raise ValueError("Use the experiment's local teacher service on port 8766")
        self.url = url
        self.opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        self.session = session
        self.task = task
        self.output_dir = output_dir
        self.lock = anyio.Lock()
        self.inflight = set()
        self.tool_count = 0
        self.checks = 0
        self.next_check = 20
        self.wait_seconds = 0.0
        self.wait_started = None
        self.error = None
        self.events = []
        hint_path = os.getenv("APPEND_SYSTEM_PROMPT_FILE")
        self.current_hint = Path(hint_path).read_text(encoding="utf-8") if hint_path else ""

    def save_state(self):
        state = {
            "session": self.session, "tool_count": self.tool_count,
            "checks": self.checks, "inflight": sorted(self.inflight),
            "teacher_wait_seconds": self.wait_seconds,
            "teacher_wait_started": self.wait_started, "error": self.error,
        }
        (self.output_dir / "online_teacher_state.json").write_text(
            json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8"
        )

    def request_hint(self, payload):
        request = urllib.request.Request(
            self.url, data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"}, method="POST",
        )
        with self.opener.open(request, timeout=660) as response:
            return json.load(response)

    async def on_tool(self, data, tool_use_id, context):
        if data.get("agent_id"):
            return {}
        async with self.lock:
            if self.error:
                return {"continue_": False, "stopReason": self.error}
            event = data["hook_event_name"]
            call_id = data["tool_use_id"]
            if event == "PreToolUse":
                self.inflight.add(call_id)
                self.save_state()
                return {}
            self.inflight.discard(call_id)
            self.tool_count += 1
            self.events.append(dict(data))
            self.save_state()
            if self.inflight or self.tool_count < self.next_check or self.checks >= 3:
                return {}

            self.checks += 1
            self.next_check = self.tool_count + 20
            transcript = Path(data["transcript_path"]).read_text(encoding="utf-8")
            payload = {
                "session": self.session, "task": self.task,
                "trajectory": transcript + "\n" + json.dumps(data, ensure_ascii=False),
                "current_hint": self.current_hint, "tool_count": self.tool_count,
            }
            self.wait_started = time.time()
            started = time.monotonic()
            self.save_state()
            try:
                result = await anyio.to_thread.run_sync(self.request_hint, payload)
                hint = result.get("hint") or ""
                self.events.append({"check": self.checks, "tool_count": self.tool_count,
                                    "hint": hint, "result": result})
                if result.get("stopped"):
                    self.error = result.get("stop_reason") or "Teacher guidance stopped"
                    return {"continue_": False, "stopReason": self.error}
                if hint:
                    return {"hookSpecificOutput": {
                        "hookEventName": event,
                        "additionalContext": "Teacher guidance:\n" + hint,
                    }}
                return {}
            except Exception as exc:
                self.error = "Teacher guidance request failed: " + str(exc)
                return {"continue_": False, "stopReason": self.error}
            finally:
                self.wait_seconds += time.monotonic() - started
                self.wait_started = None
                self.save_state()
                (self.output_dir / "online_teacher_events.json").write_text(
                    json.dumps(self.events, ensure_ascii=False, indent=2), encoding="utf-8"
                )


